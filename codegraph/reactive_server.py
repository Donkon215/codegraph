@dataclass
class ServerConfig:
    """Configuration for the reactive server."""

    interval: float = DEFAULT_POLL_INTERVAL
    json_mode: bool = False
    quiet: bool = False
    simulate: bool = False
    max_prompts_per_cycle: int = 10


@dataclass
class ReactiveEvent:
    """A single reactive event (one analysis cycle)."""

    changed_files: List[str]
    prompts: List[ReactivePrompt]
    timestamp: str = ""
    cycle: int = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "cycle": self.cycle,
            "changed_files": self.changed_files,
            "prompts": [p.to_dict() for p in self.prompts],
            "timestamp": self.timestamp,
        }


class ReactiveServer:
    """The reactive intelligence loop orchestrator.

    Polls for file changes → runs intelligence → generates prompts → writes feedback.
    """

    def __init__(
        self,
        project_root: Path,
        config: Optional[ServerConfig] = None,
    ):
        self.project_root = project_root
        self.config = config or ServerConfig()
        self.watcher = make_file_watcher(
            project_root,
            interval=self.config.interval,
        )
        self.writer = FeedbackWriter(
            project_root,
            json_mode=self.config.json_mode,
            quiet=self.config.quiet,
        )
        self.prompt_engine = PromptEngine()
        self._cycle = 0
        self._events: List[ReactiveEvent] = []

    def _analyze_file(
        self, file_path: str, *, batch_size: int = 1,
    ) -> List[ReactivePrompt]:
        """Run the intelligence loop on a single changed file and generate prompts.

        Adaptive loop compression:
            - small  (batch 1-2): focus only — fast, low overhead
            - medium (batch 3-5): focus + decide
            - large  (batch 6+):  focus + decide + simulate
        """
        from codegraph.utils.formatting import iso_now

        timestamp = iso_now()
        target = file_path

        # Determine analysis depth from batch size
        run_decide = batch_size >= 3
        run_simulate = batch_size >= 6 or self.config.simulate

        # Step 1: Focus context (always)
        focus_dict: Dict[str, Any] = {}
        try:
            from codegraph.copilot_context_builder import focus_context
            focus = focus_context(self.project_root, target)
            focus_dict = focus.to_dict()
        except Exception as exc:
            logger.debug("Focus failed for %s: %s", target, exc)

        # Escalate to decide if focus reveals violations or medium+ smells
        if not run_decide and focus_dict:
            if focus_dict.get("violations"):
                run_decide = True
            smells = focus_dict.get("smells", [])
            if any(s.get("severity") in ("medium", "high", "critical") for s in smells):
                run_decide = True

        # Step 2: Decision (medium+ or escalated)
        decision_dict: Dict[str, Any] = {}
        if run_decide:
            try:
                from codegraph.copilot_intelligence import decide
                decision = decide(self.project_root, target)
                decision_dict = decision.to_dict()
            except Exception as exc:
                logger.debug("Decide failed for %s: %s", target, exc)

            # Escalate to simulate if decision risk is high
            if not run_simulate and decision_dict.get("risk") == "high":
                run_simulate = True

        # Step 3: Simulation (large or escalated)
        simulation_dict: Dict[str, Any] = {}
        deep_sim_dict: Dict[str, Any] = {}
        if run_simulate:
            try:
                from codegraph.copilot_intelligence import _try_simulate, Decision

                if decision_dict:
                    d = Decision(
                        decision_id=decision_dict.get("decision_id", ""),
                        target=target,
                        action=decision_dict.get("action", ""),
                    )
                    simulation_dict = _try_simulate(self.project_root, target, d)
            except Exception as exc:
                logger.debug("Simulation failed for %s: %s", target, exc)

            try:
                from codegraph.copilot_intelligence import _deep_simulate
                from codegraph.copilot_context_builder import focus_context as _fc2

                fc = _fc2(self.project_root, target)
                deep_sim_dict = _deep_simulate(self.project_root, target, fc)
            except Exception as exc:
                logger.debug("Deep simulation failed for %s: %s", target, exc)

        # Step 4: Generate prompts
        prompts = self.prompt_engine.generate(
            target,
            focus=focus_dict,
            decision=decision_dict,
            simulation=simulation_dict,
            deep_sim=deep_sim_dict,
            timestamp=timestamp,
        )

        return prompts[:self.config.max_prompts_per_cycle]

    def run_once(self, changed_files: Optional[List[str]] = None) -> ReactiveEvent:
        """Run one analysis cycle on the given files (or auto-detect).

        Useful for testing or one-shot mode.
        """
        from codegraph.utils.formatting import iso_now

        if changed_files is None:
            changes = self.watcher.detect_changes()
            changed_files = [c.path for c in changes]

        self._cycle += 1
        all_prompts: List[ReactivePrompt] = []

        for fpath in changed_files:
            if not fpath.endswith(".py"):
                continue
            try:
                file_prompts = self._analyze_file(
                    fpath, batch_size=len(changed_files),
                )
                all_prompts.extend(file_prompts)
            except Exception as exc:
                logger.warning("Analysis failed for %s: %s", fpath, exc)

        # Write feedback
        if all_prompts:
            self.writer.write(all_prompts)
            if self.config.json_mode:
                self.writer.write_json(all_prompts)

        event = ReactiveEvent(
            changed_files=changed_files,
            prompts=all_prompts,
            timestamp=iso_now(),
            cycle=self._cycle,
        )
        self._events.append(event)
        return event

    def run_loop(self, max_cycles: int = 0) -> None:
        """Run the polling loop until stopped.

        Args:
            max_cycles: Stop after N cycles. 0 = run forever.
        """
        self.watcher.take_snapshot()
        self.watcher._running = True

        if not self.config.quiet:
            print(f"[codegraph server] Watching {self.project_root} "
                  f"(interval={self.config.interval}s)")

        try:
            while self.watcher.running:
                changes = self.watcher.detect_changes()

                if changes:
                    changed_files = [c.path for c in changes]
                    if not self.config.quiet:
                        print(f"\n[codegraph server] Detected {len(changes)} change(s): "
                              f"{', '.join(changed_files[:5])}")

                    self.run_once(changed_files)

                if max_cycles and self._cycle >= max_cycles:
                    break

                time.sleep(self.watcher.interval)

        except KeyboardInterrupt:
            if not self.config.quiet:
                print("\n[codegraph server] Stopped.")
        finally:
            self.watcher.stop()

    @property
    def events(self) -> List[ReactiveEvent]:
        return list(self._events)

    @property
    def cycle_count(self) -> int:
        return self._cycle
