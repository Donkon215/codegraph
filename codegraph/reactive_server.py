# 1. Prompt Engine — Classify and Generate
# ═══════════════════════════════════════════════════════════════════════

PROMPT_VIOLATION = "violation"
PROMPT_DECISION = "decision"
PROMPT_RISK = "risk"
PROMPT_OPTIMIZATION = "optimization"
PROMPT_INFO = "info"


@dataclass
class PromptContext:
    """Linked context for a prompt — affected modules, paths, subsystem."""

    affected_modules: List[str] = field(default_factory=list)
    path: str = ""  # dependency path, e.g. "A → B → C"
    subsystem: str = ""
    fan_in: int = 0
    fan_out: int = 0

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {}
        if self.affected_modules:
            d["affected_modules"] = self.affected_modules
        if self.path:
            d["path"] = self.path
        if self.subsystem:
            d["subsystem"] = self.subsystem
        if self.fan_in:
            d["fan_in"] = self.fan_in
        if self.fan_out:
            d["fan_out"] = self.fan_out
        return d

    def format_markdown(self) -> str:
        lines: List[str] = []
        if self.affected_modules:
            lines.append(f"- Affected modules: {', '.join(self.affected_modules)}")
        if self.path:
            lines.append(f"- Path: {self.path}")
        if self.subsystem:
            lines.append(f"- Subsystem: {self.subsystem}")
        if self.fan_in or self.fan_out:
            lines.append(f"- Fan-in: {self.fan_in}, Fan-out: {self.fan_out}")
        return "\n".join(lines)


@dataclass
class ReactivePrompt:
    """A single feedback prompt generated by the reactive loop.

    Designed as a *behavioral control signal* — not just information,
    but a directive that tells Copilot exactly what to do next.
    """

    prompt_type: str = PROMPT_INFO  # violation | decision | risk | optimization | info
    severity: str = "low"  # low | medium | high | critical
    priority: str = "LOW"  # LOW | MEDIUM | HIGH
    blocking: bool = False  # True = must resolve before proceeding
    title: str = ""
    body: str = ""
    target: str = ""
    suggested_commands: List[str] = field(default_factory=list)
    context: PromptContext = field(default_factory=PromptContext)
    timestamp: str = ""

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "prompt_type": self.prompt_type,
            "severity": self.severity,
            "priority": self.priority,
            "blocking": self.blocking,
            "title": self.title,
            "body": self.body,
            "target": self.target,
            "suggested_commands": self.suggested_commands,
            "timestamp": self.timestamp,
        }
        ctx = self.context.to_dict()
        if ctx:
            d["context"] = ctx
        return d

    def format_markdown(self) -> str:
        """Render as behavioral control Markdown — ACTION REQUIRED format."""
        icon = {
            PROMPT_VIOLATION: "\u2757",   # ❗
            PROMPT_RISK: "\u26a0\ufe0f",  # ⚠️
            PROMPT_OPTIMIZATION: "\U0001f3af",  # 🎯
            PROMPT_DECISION: "\U0001f9e0",  # 🧠
            PROMPT_INFO: "\u2139\ufe0f",  # ℹ️
        }.get(self.prompt_type, "\u2139\ufe0f")

        # Priority + blocking header
        if self.blocking:
            header = f"{icon} **{self.priority} PRIORITY (BLOCKING)** — {self.title}"
        else:
            header = f"{icon} **{self.priority} PRIORITY** — {self.title}"

        lines = [header]

        if self.body:
            lines.append(f"\n{self.body}")

        # Context linking
        ctx_md = self.context.format_markdown()
        if ctx_md:
            lines.append(f"\n**Context:**\n{ctx_md}")

        # Behavioral control: mandatory next steps
        if self.suggested_commands:
            if self.blocking:
                lines.append("\n**NEXT STEP (MANDATORY):**")
            else:
                lines.append("\n**Suggested action:**")
            for i, cmd in enumerate(self.suggested_commands, 1):
                lines.append(f"{i}. `{cmd}`")

        if self.blocking:
            lines.append("\n> **DO NOT** proceed without resolving this.")

        lines.append("")
        return "\n".join(lines)

    def format_terminal(self) -> str:
        """Render as concise terminal output (no Markdown)."""
        prefix = {
            PROMPT_VIOLATION: "[VIOLATION]",
            PROMPT_RISK: "[RISK]",
            PROMPT_OPTIMIZATION: "[OPTIMIZE]",
            PROMPT_DECISION: "[DECISION]",
            PROMPT_INFO: "[INFO]",
        }.get(self.prompt_type, "[INFO]")

        blocking_tag = " BLOCKING" if self.blocking else ""
        parts = [f"{prefix} [{self.priority}{blocking_tag}] {self.title}"]
        if self.body:
            parts.append(f"  {self.body}")
        if self.context.affected_modules:
            parts.append(f"  Affects: {', '.join(self.context.affected_modules)}")
        if self.context.subsystem:
            parts.append(f"  Subsystem: {self.context.subsystem}")
        for cmd in self.suggested_commands:
            parts.append(f"  -> {cmd}")
        if self.blocking:
            parts.append("  !! MUST RESOLVE BEFORE PROCEEDING")
        return "\n".join(parts)


class PromptEngine:
    """Analyze intelligence results and generate typed prompts.

    Computes priority (HIGH/MEDIUM/LOW), blocking flag, and context
    linking (affected modules, paths, subsystem) for each prompt.
    """

    @staticmethod
    def _build_context(
        focus: Optional[Dict[str, Any]] = None,
    ) -> PromptContext:
        """Extract context-linking data from focus dict."""
        ctx = PromptContext()
        if not focus:
            return ctx
        # Affected modules: callees from focus
        callees = focus.get("callees", [])
        callers = focus.get("callers", [])
        ctx.affected_modules = list(dict.fromkeys(callers[:5] + callees[:5]))
        ctx.subsystem = focus.get("subsystem", "")
        ctx.fan_in = focus.get("fan_in", 0)
        ctx.fan_out = focus.get("fan_out", 0)
        # Build path from edges if available
        edges = focus.get("edges", [])
        if edges:
            path_parts: List[str] = []
            for e in edges[:4]:
                src = e.get("source", "").split("::")[-1]
                tgt = e.get("target", "").split("::")[-1]
                if src and tgt:
                    if not path_parts:
                        path_parts.append(src)
                    path_parts.append(tgt)
            if path_parts:
                ctx.path = " \u2192 ".join(dict.fromkeys(path_parts))
        return ctx

    @staticmethod
    def _compute_priority(
        prompt_type: str, severity: str, blocking: bool
    ) -> str:
        """Compute priority from type + severity."""
        if blocking:
            return "HIGH"
        if severity in ("critical", "high"):
            return "HIGH"
        if severity == "medium":
            return "MEDIUM"
        if prompt_type == PROMPT_VIOLATION:
            return "HIGH"
        return "LOW"

    @staticmethod
    def generate(
        target: str,
        *,
        focus: Optional[Dict[str, Any]] = None,
        decision: Optional[Dict[str, Any]] = None,
        simulation: Optional[Dict[str, Any]] = None,
        deep_sim: Optional[Dict[str, Any]] = None,
        timestamp: str = "",
    ) -> List[ReactivePrompt]:
        """Generate prompts from intelligence loop results.

        Takes the dict outputs of focus_context, decide, copilot_loop.
        Returns a list of prompts sorted by severity (critical first).
        """
        prompts: List[ReactivePrompt] = []

        # Build context once from focus data
        ctx = PromptEngine._build_context(focus)

        # --- 1. Violation prompts ---
        if focus:
            violations = focus.get("violations", [])
            for v in violations:
                msg = v if isinstance(v, str) else str(v)
                _blk = True
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_VIOLATION,
                    severity="high",
                    priority=PromptEngine._compute_priority(PROMPT_VIOLATION, "high", _blk),
                    blocking=_blk,
                    title=f"Violation in {target}",
                    body=msg,
                    target=target,
                    suggested_commands=[
                        f"codegraph focus {target} --json",
                        f"codegraph decide {target} --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

            # Smells → optimization prompts
            smells = focus.get("smells", [])
            for smell in smells:
                smell_type = smell.get("smell_type", "unknown")
                desc = smell.get("description", "")
                sev = "medium" if smell.get("severity") == "medium" else "low"
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_OPTIMIZATION,
                    severity=sev,
                    priority=PromptEngine._compute_priority(PROMPT_OPTIMIZATION, sev, False),
                    blocking=False,
                    title=f"Smell ({smell_type}) in {target}",
                    body=desc,
                    target=target,
                    suggested_commands=[
                        f"codegraph decide {target} --json",
                        f"codegraph scenario --components {target} --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

        # --- 2. Decision prompts ---
        if decision:
            action = decision.get("action", "")
            confidence = decision.get("confidence", 0)
            risk = decision.get("risk", "low")
            reason = decision.get("reason", "")

            if action == "fix_violations":
                _sev = "high" if risk == "high" else "medium"
                _blk = risk == "high"
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_DECISION,
                    severity=_sev,
                    priority=PromptEngine._compute_priority(PROMPT_DECISION, _sev, _blk),
                    blocking=_blk,
                    title=f"Decision: {action} ({target})",
                    body=f"{reason}\nConfidence: {confidence:.0%}, Risk: {risk}",
                    target=target,
                    suggested_commands=decision.get("next_steps", []),
                    context=ctx,
                    timestamp=timestamp,
                ))
            elif action != "safe_to_edit":
                _sev = "medium" if risk != "low" else "low"
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_DECISION,
                    severity=_sev,
                    priority=PromptEngine._compute_priority(PROMPT_DECISION, _sev, False),
                    blocking=False,
                    title=f"Decision: {action} ({target})",
                    body=f"{reason}\nConfidence: {confidence:.0%}",
                    target=target,
                    suggested_commands=decision.get("next_steps", []),
                    context=ctx,
                    timestamp=timestamp,
                ))

        # --- 3. Risk prompts (from simulation) ---
        if simulation:
            cycle_risk = simulation.get("cycle_risk", 0)
            coupling_delta = simulation.get("coupling_delta", 0)

            if cycle_risk > 0:
                _sev = "high" if cycle_risk > 2 else "medium"
                _blk = cycle_risk > 2
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_RISK,
                    severity=_sev,
                    priority=PromptEngine._compute_priority(PROMPT_RISK, _sev, _blk),
                    blocking=_blk,
                    title=f"Cycle risk: {cycle_risk} new cycle(s)",
                    body=f"Simulation predicts {cycle_risk} cycle(s) if {target} is modified.",
                    target=target,
                    suggested_commands=[
                        f"codegraph copilot-loop {target} --simulate --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

            if coupling_delta > 0.05:
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_RISK,
                    severity="medium",
                    priority=PromptEngine._compute_priority(PROMPT_RISK, "medium", False),
                    blocking=False,
                    title=f"Coupling increase: +{coupling_delta:.2f}",
                    body=f"Change to {target} increases coupling.",
                    target=target,
                    suggested_commands=[
                        f"codegraph focus {target} --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

        # --- 3b. Deep simulation risk prompts ---
        if deep_sim:
            failure_chains = deep_sim.get("failure_chains", [])
            if failure_chains:
                chain_count = len(failure_chains)
                preview = failure_chains[0] if failure_chains else ""
                _sev = "high" if chain_count >= 3 else "medium"
                _blk = chain_count >= 3
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_RISK,
                    severity=_sev,
                    priority=PromptEngine._compute_priority(PROMPT_RISK, _sev, _blk),
                    blocking=_blk,
                    title=f"Failure propagation: {chain_count} chain(s)",
                    body=f"Example: {preview}" if preview else "",
                    target=target,
                    suggested_commands=[
                        f"codegraph copilot-loop {target} --simulate --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

            data_flow = deep_sim.get("data_flow_edges_affected", 0)
            if data_flow >= 3:
                prompts.append(ReactivePrompt(
                    prompt_type=PROMPT_RISK,
                    severity="medium",
                    priority=PromptEngine._compute_priority(PROMPT_RISK, "medium", False),
                    blocking=False,
                    title=f"Data flow impact: {data_flow} edge(s) affected",
                    body=f"Changes to {target} affect {data_flow} data flow edges.",
                    target=target,
                    suggested_commands=[
                        f"codegraph focus {target} --json",
                    ],
                    context=ctx,
                    timestamp=timestamp,
                ))

        # --- 4. Optimization prompts (from decision alternatives) ---
        if decision:
            for alt in decision.get("alternatives", []):
                alt_action = alt.get("action", "")
                alt_reason = alt.get("reason_rejected", "")
                if alt_action and "split" in alt_action.lower():
                    prompts.append(ReactivePrompt(
                        prompt_type=PROMPT_OPTIMIZATION,
                        severity="low",
                        priority="LOW",
                        blocking=False,
                        title=f"Alternative: {alt_action}",
                        body=f"Not chosen because: {alt_reason}",
                        target=target,
                        suggested_commands=[
                            f"codegraph scenario --components {target} --json",
                        ],
                        context=ctx,
                        timestamp=timestamp,
                    ))

        # Sort: HIGH blocking first, then by severity
        def _sort_key(p: ReactivePrompt) -> tuple:
            priority_order = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
            severity_order = {"critical": 0, "high": 1, "medium": 2, "low": 3}
            return (
                0 if p.blocking else 1,
                priority_order.get(p.priority, 3),
                severity_order.get(p.severity, 4),
            )

        prompts.sort(key=_sort_key)

        return prompts


