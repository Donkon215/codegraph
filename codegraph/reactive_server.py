# 2. Feedback Writer — Deliver Prompts
# ═══════════════════════════════════════════════════════════════════════

FEEDBACK_FILE = "feedback.md"


class FeedbackWriter:
    """Write prompts to .codegraph/feedback.md and optionally to a callback."""

    def __init__(
        self,
        project_root: Path,
        *,
        terminal_callback: Optional[Callable[[str], None]] = None,
        json_mode: bool = False,
        quiet: bool = False,
    ):
        self.project_root = project_root
        self.feedback_dir = project_root / ".codegraph"
        self.feedback_path = self.feedback_dir / FEEDBACK_FILE
        self.terminal_callback = terminal_callback
        self.json_mode = json_mode
        self.quiet = quiet

    def write(self, prompts: List[ReactivePrompt], *, append: bool = False) -> Path:
        """Write prompts to feedback.md and optionally echo to terminal.

        Prompts are grouped: BLOCKING items appear first under a
        dedicated header so Copilot sees them immediately.

        Returns the path to the feedback file.
        """
        self.feedback_dir.mkdir(parents=True, exist_ok=True)

        blocking = [p for p in prompts if p.blocking]
        non_blocking = [p for p in prompts if not p.blocking]

        # Build Markdown content
        lines: List[str] = []
        if not append:
            lines.append("# Codegraph Reactive Feedback\n")
            lines.append(
                "> Auto-generated by `codegraph server`. "
                "Read by Copilot for architecture-aware editing.\n"
            )

        if blocking:
            lines.append("## BLOCKING — Resolve Before Proceeding\n")
            for prompt in blocking:
                lines.append(prompt.format_markdown())
                lines.append("---\n")

        if non_blocking:
            if blocking:
                lines.append("## Advisory\n")
            for prompt in non_blocking:
                lines.append(prompt.format_markdown())
                lines.append("---\n")

        content = "\n".join(lines)

        # Write file
        mode = "a" if append else "w"
        with open(self.feedback_path, mode, encoding="utf-8") as f:
            f.write(content)

        # Terminal output
        if not self.quiet:
            for prompt in prompts:
                if self.json_mode:
                    text = json.dumps(prompt.to_dict(), indent=2)
                else:
                    text = prompt.format_terminal()

                if self.terminal_callback:
                    self.terminal_callback(text)
                else:
                    print(text)

        return self.feedback_path

    def write_json(self, prompts: List[ReactivePrompt]) -> Path:
        """Write prompts as JSON array to .codegraph/feedback.json."""
        json_path = self.feedback_dir / "feedback.json"
        data = [p.to_dict() for p in prompts]
        json_path.write_text(
            json.dumps(data, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        return json_path


