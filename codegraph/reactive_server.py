# 3. File Watcher — Polling-based (no external deps)
# ═══════════════════════════════════════════════════════════════════════

DEFAULT_POLL_INTERVAL = 2.0  # seconds
DEBOUNCE_WINDOW = 1.0  # seconds — ignore rapid re-fires


@dataclass
class FileChange:
    """A detected file change."""

    path: str  # relative to project root
    change_type: str  # modified | created | deleted
    mtime: float = 0.0


class FileWatcher:
    """Poll-based Python file watcher.

    Scans project root for .py files, tracks mtime, detects changes.
    No external dependencies required.
    """

    def __init__(
        self,
        project_root: Path,
        *,
        interval: float = DEFAULT_POLL_INTERVAL,
        extensions: Optional[Set[str]] = None,
        exclude_dirs: Optional[Set[str]] = None,
    ):
        self.project_root = project_root
        self.interval = max(interval, 0.5)
        self.extensions = extensions or {".py"}
        self.exclude_dirs = exclude_dirs or {
            ".codegraph", "__pycache__", ".git", ".venv", "venv",
            "node_modules", ".tox", ".mypy_cache", ".pytest_cache",
            "dist", "build", ".eggs", "*.egg-info",
        }
        self._snapshot: Dict[str, float] = {}
        self._last_change_time: Dict[str, float] = {}
        self._running = False

    def _should_exclude(self, path: Path) -> bool:
        """Check if a path should be excluded."""
        parts = path.parts
        for part in parts:
            if part in self.exclude_dirs:
                return True
            # Handle glob-like patterns like *.egg-info
            for excl in self.exclude_dirs:
                if "*" in excl and part.endswith(excl.lstrip("*")):
                    return True
        return False

    def _scan(self) -> Dict[str, float]:
        """Scan project for tracked files and return {rel_path: mtime}."""
        snapshot: Dict[str, float] = {}
        try:
            for root_dir, dirs, files in os.walk(self.project_root):
                root_path = Path(root_dir)
                rel_root = root_path.relative_to(self.project_root)

                if self._should_exclude(rel_root):
                    dirs.clear()
                    continue

                # Prune excluded dirs for os.walk
                dirs[:] = [
                    d for d in dirs
                    if not self._should_exclude(rel_root / d)
                ]

                for fname in files:
                    if not any(fname.endswith(ext) for ext in self.extensions):
                        continue
                    fpath = root_path / fname
                    try:
                        mtime = fpath.stat().st_mtime
                        rel = str(fpath.relative_to(self.project_root)).replace("\\", "/")
                        snapshot[rel] = mtime
                    except (OSError, ValueError):
                        continue
        except OSError:
            pass
        return snapshot

    def take_snapshot(self) -> None:
        """Take initial snapshot of file state."""
        self._snapshot = self._scan()

    def detect_changes(self) -> List[FileChange]:
        """Compare current state to snapshot and return changes.

        Debounces: ignores files that changed within DEBOUNCE_WINDOW.
        """
        current = self._scan()
        now = time.monotonic()
        changes: List[FileChange] = []

        # Modified or created
        for path, mtime in current.items():
            old_mtime = self._snapshot.get(path)
            if old_mtime is None:
                # New file
                last = self._last_change_time.get(path, 0)
                if now - last >= DEBOUNCE_WINDOW:
                    changes.append(FileChange(path=path, change_type="created", mtime=mtime))
                    self._last_change_time[path] = now
            elif mtime != old_mtime:
                # Modified
                last = self._last_change_time.get(path, 0)
                if now - last >= DEBOUNCE_WINDOW:
                    changes.append(FileChange(path=path, change_type="modified", mtime=mtime))
                    self._last_change_time[path] = now

        # Deleted
        for path in self._snapshot:
            if path not in current:
                changes.append(FileChange(path=path, change_type="deleted"))

        # Update snapshot
        self._snapshot = current
        return changes

    @property
    def running(self) -> bool:
        return self._running

    def stop(self) -> None:
        self._running = False


