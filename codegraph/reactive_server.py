# 3b. WatchdogFileWatcher — OS-level event-driven watcher (optional)
# ═══════════════════════════════════════════════════════════════════════

if _WATCHDOG_AVAILABLE:
    class _CodegraphEventHandler(FileSystemEventHandler):  # type: ignore[misc]
        """Collect watchdog events into a thread-safe queue."""

        def __init__(
            self,
            project_root: Path,
            extensions: Set[str],
            exclude_dirs: Set[str],
            event_queue: "queue.Queue[FileChange]",
        ) -> None:
            super().__init__()
            self._root = project_root
            self._extensions = extensions
            self._exclude_dirs = exclude_dirs
            self._queue = event_queue
            self._debounce: Dict[str, float] = {}

        def _should_ignore(self, src_path: str) -> bool:
            try:
                rel = Path(src_path).relative_to(self._root)
            except ValueError:
                return True
            # Extension filter
            if not any(str(rel).endswith(ext) for ext in self._extensions):
                return True
            # Directory exclusions
            parts = rel.parts
            for part in parts[:-1]:  # skip the filename itself
                if part in self._exclude_dirs:
                    return True
                for excl in self._exclude_dirs:
                    if "*" in excl and part.endswith(excl.lstrip("*")):
                        return True
            return False

        def _enqueue(self, change_type: str, src_path: str) -> None:
            if self._should_ignore(src_path):
                return
            now = time.monotonic()
            last = self._debounce.get(src_path, 0.0)
            if now - last < DEBOUNCE_WINDOW:
                return
            self._debounce[src_path] = now
            try:
                rel = str(Path(src_path).relative_to(self._root)).replace("\\", "/")
            except ValueError:
                return
            mtime = 0.0
            if change_type != "deleted":
                try:
                    mtime = Path(src_path).stat().st_mtime
                except OSError:
                    return
            self._queue.put(FileChange(path=rel, change_type=change_type, mtime=mtime))

        def on_modified(self, event: "FileSystemEvent") -> None:
            if not event.is_directory:
                self._enqueue("modified", event.src_path)

        def on_created(self, event: "FileSystemEvent") -> None:
            if not event.is_directory:
                self._enqueue("created", event.src_path)

        def on_deleted(self, event: "FileSystemEvent") -> None:
            if not event.is_directory:
                self._enqueue("deleted", event.src_path)

        def on_moved(self, event: "FileSystemEvent") -> None:
            if not event.is_directory:
                self._enqueue("deleted", event.src_path)
                self._enqueue("created", event.dest_path)

    class WatchdogFileWatcher:
        """OS-level event-driven file watcher powered by watchdog.

        Drops the polling overhead entirely; events arrive via inotify /
        FSEvents / ReadDirectoryChangesW.  Public API is identical to
        ``FileWatcher`` so ``ReactiveServer`` uses either transparently.
        """

        def __init__(
            self,
            project_root: Path,
            *,
            interval: float = DEFAULT_POLL_INTERVAL,  # kept for API compat, unused
            extensions: Optional[Set[str]] = None,
            exclude_dirs: Optional[Set[str]] = None,
        ) -> None:
            self.project_root = project_root
            self.interval = interval
            self.extensions = extensions or {".py"}
            self.exclude_dirs = exclude_dirs or {
                ".codegraph", "__pycache__", ".git", ".venv", "venv",
                "node_modules", ".tox", ".mypy_cache", ".pytest_cache",
                "dist", "build", ".eggs", "*.egg-info",
            }
            self._event_queue: "queue.Queue[FileChange]" = queue.Queue()
            self._observer: Optional["_WatchdogObserver"] = None
            self._running = False

        def take_snapshot(self) -> None:
            """Start the watchdog observer (no snapshot needed)."""
            handler = _CodegraphEventHandler(
                self.project_root,
                self.extensions,
                self.exclude_dirs,
                self._event_queue,
            )
            self._observer = _WatchdogObserver()
            self._observer.schedule(handler, str(self.project_root), recursive=True)
            self._observer.start()
            self._running = True

        def detect_changes(self) -> List[FileChange]:
            """Drain the event queue and return accumulated changes."""
            changes: List[FileChange] = []
            try:
                while True:
                    changes.append(self._event_queue.get_nowait())
            except queue.Empty:
                pass
            return changes

        @property
        def running(self) -> bool:
            return self._running

        def stop(self) -> None:
            self._running = False
            if self._observer is not None:
                self._observer.stop()
                self._observer.join(timeout=5)
                self._observer = None


def make_file_watcher(
    project_root: Path,
    *,
    interval: float = DEFAULT_POLL_INTERVAL,
    extensions: Optional[Set[str]] = None,
    exclude_dirs: Optional[Set[str]] = None,
) -> "FileWatcher | WatchdogFileWatcher":
    """Return the best available file watcher for this environment.

    Uses watchdog (OS-level events) when installed; falls back to
    polling-based ``FileWatcher`` otherwise.  Both share the same API
    so callers don't need to branch.
    """
    if _WATCHDOG_AVAILABLE:
        logger.debug("Using watchdog-based file watcher")
        return WatchdogFileWatcher(  # type: ignore[return-value]
            project_root,
            interval=interval,
            extensions=extensions,
            exclude_dirs=exclude_dirs,
        )
    logger.debug("watchdog not installed; using polling file watcher")
    return FileWatcher(
        project_root,
        interval=interval,
        extensions=extensions,
        exclude_dirs=exclude_dirs,
    )


