"""codegraph.reactive_server — Push-model Reactive Intelligence Loop.

Architecture:

    File System  →  FileWatcher  →  ReactiveServer  →  PromptEngine  →  FeedbackWriter
                  (watchdog/poll)    (orchestrate)      (classify)       (deliver)

The server watches for file changes, runs the intelligence loop on
affected files, generates short/actionable/contextual prompts, and
writes feedback to:
    - `.codegraph/feedback.md` (for Copilot / editors to read)
    - terminal (for human visibility)

Prompt Types:
    1. ViolationPrompt   — architecture boundary crossed
    2. DecisionPrompt    — pattern match / memory-influenced advice
    3. RiskPrompt        — failure propagation / simulation warning
    4. OptimizationPrompt — better alternative found

File Watching:
    Prefers watchdog (OS-level inotify/FSEvents/ReadDirectoryChangesW) when
    available (``pip install codegraph[watch]``). Falls back to polling when
    watchdog is not installed. Both expose the same ``FileWatcher`` API so
    the rest of the server is unchanged.

CLI: ``codegraph server [--interval N] [--json] [--quiet]``
"""

